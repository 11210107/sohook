bool send_wwmessage_from_db(const std::vector<uint64_t> &id_list,
                            std::function<void(int64_t, int64_t, uint64_t)> onProgress,
                            std::function<void(int, uint64_t)> onResult) {
    // 1) DB 十六进制 → 原始字节（等价读 DB 列后取 BLOB）
    std::vector<uint8_t> content_pb, extra_pb;
    if (!rawpb::parse_hex_stream(kDbMiniProgramContentHex, content_pb) ||
        !rawpb::parse_hex_stream(kDbVideoExtraHex, extra_pb)) {
        LOGE("[wwmessage] DB hex 解析失败 (content %zuB / extra %zuB)",
             content_pb.size(), extra_pb.size());
        return false;
    }
    uint32_t content_type = 78;
    // 2) 三字段 → 出站 PB。generate_wwmessage_pb 内部：
    //    Tag7=content_type、Tag10=content、Tag19=extra（解析失败自动弃扩展保 content）
    std::vector<uint8_t> pb = generate_wwmessage_pb(content_type,content_pb);
    // dump_protobuf_hex(pb);
    if (pb.empty()) {
        LOGE("[wwmessage] DB 重构序列化失败");
        return false;
    }
    LOGI("[wwmessage] DB 重构出站 %zu 字节 (content %zu + extra %zu)，目标 %zu 个会话",
         pb.size(), content_pb.size(), extra_pb.size(), id_list.size());
    // 3) 群发：msg_type 直接传 content_type(13)；PB 与接收者无关，生成一次循环多发
    for (uint64_t cid: id_list) {
        usleep(50000); // 给底层 TaskQueue/网络线程让出缓冲（与图片路径一致）
        send_model_message(cid, 13, pb, onProgress, onResult);
    }
    return true;
}
